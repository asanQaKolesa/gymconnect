// src/data/defaultTrainerRules.js

export const CANCELLATION_HOURS_OPTIONS = [2, 4, 12, 24];
export const FREEZE_DAYS_OPTIONS = [0, 7, 14];
export const VALIDITY_DAYS_OPTIONS = [30, 35, 45, 60];

export const DEFAULT_TRAINER_RULES = {
  cancellationHoursLimit: 4,
  freezeMaxDays: 7,
  freezeMaxCount: 1,
  packageValidityDays: 35,
  singleSessionPrice: 7000,
  refundPolicyType: 'recalculate_as_single', // перерасчет пройденных по разовому тарифу
  lateGraceMinutes: 15,
  customNotes: 'Тренировки проводятся по предварительной записи. При плохом самочувствии обязательно уведомите тренера заранее.',
};

/**
 * Генерация подробного юридически выверенного и уважительного текста регламента
 */
export function generateRulesFullText(rules = DEFAULT_TRAINER_RULES, coachName = 'Ваш тренер') {
  const r = { ...DEFAULT_TRAINER_RULES, ...rules };

  return `РЕГЛАМЕНТ ПЕРСОНАЛЬНЫХ ТРЕНИРОВОК
Наставник: ${coachName}

1. СРОКИ И ДЕЙСТВИЕ АБОНЕМЕНТА
1.1. Пакет персональных тренировок активируется в день проведения первого занятия либо на 7-й день после внесения оплаты.
1.2. Срок действия блока составляет ${r.packageValidityDays} календарных дней. По истечении этого срока неизрасходованные занятия аннулируются.

2. ЗАМОРОЗКА И ПЕРЕРЫВЫ
2.1. В рамках одного абонемента предоставляется возможность заморозки: максимум ${r.freezeMaxDays} дней (не более ${r.freezeMaxCount} раза за период действия абонемента).
2.2. Заморозка оформляется до наступления перерыва через личный кабинет GymConnect или уведомлением тренера.

3. ПРАВИЛА ОТМЕНЫ И ОПОЗДАНИЯ
3.1. Бесплатная отмена или перенос тренировки возможны не позднее чем за ${r.cancellationHoursLimit} часа до назначенного времени.
3.2. При отмене менее чем за ${r.cancellationHoursLimit} часа занятие считается проведенным и списывается с баланса абонемента.
3.3. В случае опоздания атлета тренировка сокращается на время задержки, чтобы не сдвигать расписание следующих подопечных.

4. ПОРЯДОК ВОЗВРАТА СРЕДСТВ
4.1. При досрочном расторжении соглашения возврат неиспользованных средств производится по формуле перерасчета: проведенные тренировки рассчитываются по стоимости разового занятия (${Number(r.singleSessionPrice).toLocaleString('ru-RU')} ₸), а оставшаяся разница возвращается клиенту.

5. ОСОБЫЕ ПОЖЕЛАНИЯ
${r.customNotes || 'Соблюдайте питьевой режим, технику безопасности и тренируйтесь с удовольствием!'}`;
}
